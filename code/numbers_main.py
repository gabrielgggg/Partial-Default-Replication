"""numbers_main.py: LaTeX macros for the numbers of the deterministic solution, the two-state chain, and the main
diffusion solution quoted in the text, and the two calibration losses.

Reads:  data/det_fine.npz, data/jump_floor.npz, data/illustrations_jump.log, data/ou_main.npz,
        data/main_moments.md; the loss of Arellano, Mateos-Planas, and Rios-Rull (2023) from amr_values.py
Writes: output/numbers.tex
Usage:  python code/numbers_main.py
"""
import os
import re

import numpy as np

from amr_values import AMR_LOSS
from cuberoot_consts import second_order
from paths import DATA, OUT


def read(f):
    """Contents of a text file in data/."""
    return open(os.path.join(DATA, f), encoding="utf-8").read()


def trim(s):
    """Drop trailing zeros of a plain decimal (0.100 -> 0.1); anything else unchanged."""
    return s.rstrip("0").rstrip(".") if re.fullmatch(r"-?\d+\.\d+", s) else s


def sci(v):
    """Scientific notation in LaTeX, one significant digit."""
    e = int(np.floor(np.log10(v)))
    return f"{v / 10 ** e:.0f}\\times10^{{{e}}}"


# main diffusion solution: calibrated parameters, underwriting standard, endowment nodes
am = np.load(os.path.join(DATA, "ou_main.npz"))
qf = float(am["qf"])

# deterministic solution (500 nodes per unit of debt): closed-form constants, and the first nodes with the price
# below the underwriting standard and with full default
fine = np.load(os.path.join(DATA, "det_fine.npz"))
Sig1, Q1 = second_order(fine, am["x"])
B, q, d = fine["B"], fine["q"], fine["d"]
ifl = np.where(q < qf)[0]
ifd = np.where(d >= 1 - 1e-9)[0]

# two-state chain: size of the states, switching rate, final pricing residual
jmp = np.load(os.path.join(DATA, "jump_floor.npz"))
resq = float(re.search(r"residuals [0-9.e+-]+ / ([0-9.e+-]+)", read("illustrations_jump.log")).group(1))

# calibration loss of the main solution
loss = float(am["loss"])      # unrounded, from the solution file: main_moments.md carries four decimals

# macro name -> value
vals = {
    "detBpd": f"{float(fine['Bpd']):.3f}", "detdfirst": f"{float(fine['dfirst']):.2f}",
    "detbeta": f"{float(fine['beta']):.3f}", "detalpha": f"{float(fine['alpha']):.2f}",
    "detSigmaOne": f"{Sig1:.3f}", "detQOne": f"{Q1:.3f}",
    "detFloorB": f"{B[ifl[0]]:.2f}", "detFullB": f"{B[ifd[0]]:.2f}",
    "jumpSd": f"{abs(jmp['z'][0]):.2f}", "jumpEta": f"{float(jmp['eta']):.3f}", "jumpResq": sci(resq),
    "mainNz": str(int(am["z"].size)),
}
with open(os.path.join(OUT, "numbers.tex"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("% generated by numbers_main.py -- do not edit\n")
    for k, v in vals.items():
        fh.write("\\newcommand{\\" + k + "}{" + trim(v) + "}\n")
    # the two losses keep three decimals
    fh.write("\\newcommand{\\calLoss}{" + f"{loss:.3f}" + "}\n")
    fh.write("\\newcommand{\\calLossAMR}{" + f"{AMR_LOSS:.3f}" + "}\n")
